"""
Extract CRCON's weapon tables (rcon/weapons.py) into TypeScript, mechanically.

    python3 -I extract-crcon-weapons.py <path to rcon/weapons.py> <out.ts>

The source is read with `ast` and never executed: WeaponType's members, the five faction dicts,
ALL_WEAPONS (merged in the order the module merges them: a later dict's value wins, the first
position stays), NO_SIDE_WEAPONS and the side map the module builds from them (US, Soviet and
British weapons are the allies'; Axis weapons the axis', written last; the Canadian dict is not
read for sides at all).
"""
import ast
import json
import sys


def main(src_path: str, out_path: str) -> None:
    tree = ast.parse(open(src_path, encoding="utf-8").read())
    weapon_types: dict[str, str] = {}
    dicts: dict[str, dict[str, str]] = {}
    lists: dict[str, list[str]] = {}
    all_weapons_node = None
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and node.name == "WeaponType":
            for stmt in node.body:
                if isinstance(stmt, ast.Assign) and isinstance(stmt.value, ast.Constant):
                    weapon_types[stmt.targets[0].id] = stmt.value.value
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            name = node.targets[0].id
            if name == "ALL_WEAPONS":
                all_weapons_node = node.value
            elif isinstance(node.value, ast.Dict) and name.endswith("_WEAPONS"):
                d: dict[str, str] = {}
                for k, v in zip(node.value.keys, node.value.values):
                    assert isinstance(k, ast.Constant) and isinstance(v, ast.Attribute) and v.value.id == "WeaponType", ast.dump(v)
                    d[k.value] = weapon_types[v.attr]
                dicts[name] = d
            elif isinstance(node.value, ast.List):
                lists[name] = [e.value for e in node.value.elts]

    # ALL_WEAPONS = {**US_WEAPONS, ..., "BOMBING RUN": WeaponType.Commander, ...}
    all_weapons: dict[str, str] = {}
    assert isinstance(all_weapons_node, ast.Dict)
    for k, v in zip(all_weapons_node.keys, all_weapons_node.values):
        if k is None:
            all_weapons.update(dicts[v.id])
        else:
            all_weapons[k.value] = weapon_types[v.attr]

    no_side = set(lists["NO_SIDE_WEAPONS"])
    sides: dict[str, str] = {}
    for w in [*dicts["US_WEAPONS"], *dicts["SOVIET_WEAPONS"], *dicts["BRITISH_WEAPONS"]]:
        if w not in no_side:
            sides[w] = "allies"
    for w in dicts["AXIS_WEAPONS"]:
        if w not in no_side:
            sides[w] = "axis"

    out = [
        "/**",
        " * CRCON v12.3.0's weapon tables (rcon/weapons.py): the WeaponType of every weapon it knows, in",
        " * ALL_WEAPONS' own order, and the side each one belongs to (WEAPON_SIDE_MAP). Generated by",
        " * apps/api/scripts/extract-crcon-weapons.py — edit the script, not this file.",
        " *",
        " * Copyright (c) 2020 Julien Marechal. MIT licence: see NOTICE.md and third_party/crcon/LICENSE.",
        " */",
        "",
        "/** [weapon, WeaponType value], in ALL_WEAPONS' order. */",
        "export const CRCON_WEAPON_TYPES: readonly (readonly [string, string])[] = [",
        *[f"  [{json.dumps(k, ensure_ascii=False)}, {json.dumps(v)}]," for k, v in all_weapons.items()],
        "];",
        "",
        "/** [weapon, side], in WEAPON_SIDE_MAP's order. */",
        "export const CRCON_WEAPON_SIDES: readonly (readonly [string, \"allies\" | \"axis\"])[] = [",
        *[f"  [{json.dumps(k, ensure_ascii=False)}, {json.dumps(v)}]," for k, v in sides.items()],
        "];",
        "",
    ]
    open(out_path, "w", encoding="utf-8").write("\n".join(out))
    print(f"{len(all_weapons)} weapons, {len(sides)} sided, types {sorted(set(all_weapons.values()))}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
